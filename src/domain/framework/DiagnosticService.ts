export class DiagnosticService {
  public info(message: string, data?: unknown): void { void message; void data; }
  public warning(message: string, data?: unknown): void { void message; void data; }
  public error(message: string, data?: unknown): void { void message; void data; }
  public record(code: string, message: string, data?: unknown): void { void code; void message; void data; }
}
